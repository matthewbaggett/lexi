// Builds the format corpus in testdata/corpus/{markdown,html,mdx}/ and records what the
// real alex 11.0.1 reports for each document. The Go test TestFormatCorpus in internal/input runs
// lexi over the files and needs no Node.
//
//   ALEX_ORACLE=<dir with alex@11.0.1> node scripts/corpus/generate-formats.mjs
//
// Each line of a testdata/corpus/<category>/<kind>.jsonl file is one document:
//   id        hash of the category and the text. Unique.
//   category  "markdown", "html" or "mdx": the alex entry point that read the text
//   kind      the construct the template aims at. It matches the file name.
//   label     "positive": the terms sit in prose, so alex reports them.
//             "negative": the terms sit in code, a comment or an attribute, so alex stays silent.
//             "edge": malformed input, control comments, or a position quirk.
//   text      the document
//   want      what alex reported: "line:col-line:col: message [source:rule-id]", sorted by
//             position. "ERROR <message>" when alex throws.
//   known     optional. A code that names a section of KNOWN_DIFFS.md. lexi differs from alex on
//             purpose for this document. The test checks that lexi still differs.
//
// The generator is deterministic: the same templates and the same alex give the same files.
