// ---------------------------------------------------------------- Tag soup
// Random sequences of tags and terms. They test the tree construction in shapes that no
// template foresees. The seed is fixed, so the documents repeat.
let soupSeed = Number(process.env.SOUP_SEED || 0x5011)
const soupRnd = () => {
  soupSeed = (soupSeed + 0x6d2b79f5) | 0
  let t = Math.imul(soupSeed ^ (soupSeed >>> 15), 1 | soupSeed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const soupPick = (list) => list[Math.floor(soupRnd() * list.length)]
const SOUP_TAGS = ['p', 'b', 'i', 'a', 'div', 'span', 'table', 'tr', 'td', 'th', 'tbody', 'thead', 'caption', 'colgroup', 'col', 'ul', 'ol', 'li', 'dl', 'dd', 'dt', 'select', 'option', 'optgroup', 'form', 'h1', 'h2', 'em', 'strong', 'pre', 'button', 'nobr', 'font', 'code', 'u', 's', 'big', 'svg', 'math', 'center', 'blockquote', 'section', 'br', 'hr', 'img', 'input', 'object', 'marquee', 'html', 'body', 'head', 'title', 'noscript', 'textarea', 'ruby', 'rt', 'address']
const soup = (a, b) => {
  const parts = []
  const n = 4 + Math.floor(soupRnd() * 10)
  for (let i = 0; i < n; i++) {
    const r = soupRnd()
    if (r < 0.3) parts.push(soupRnd() < 0.5 ? a : b)
    else if (r < 0.62) parts.push(`<${soupPick(SOUP_TAGS)}>`)
    else parts.push(`</${soupPick(SOUP_TAGS)}>`)
  }
  return parts.join(soupRnd() < 0.3 ? ' ' : '')
}
