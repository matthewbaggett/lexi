// ---------------------------------------------------------------- Modifiers
// Each modifier rewrites a whole document. The first one leaves it as it is.
const eol = (s, f) => s.replace(/\r\n|\n/g, f)
const mods = [
  ['plain', (s) => s],
  ['crlf', (s) => eol(s, () => '\r\n')],
  ['mixed', (s) => { let i = 0; return eol(s, () => (i++ % 2 ? '\n' : '\r\n')) }],
  ['lead', (s) => `café \u{1F600} 日本\n\n${s}`],
  ['noeol', (s) => s.replace(/\n+$/, '')],
  ['indent', (s) => s.split('\n').map((l) => (l ? `\t${l}` : l)).join('\n')],
]
// Modifiers that make no sense for a template are skipped, so that no document appears twice.
const skip = (kind, mod) =>
  (mod === 'crlf' || mod === 'mixed') && kind === 'lineend'

// ---------------------------------------------------------------- Run
const out = {markdown: [], html: [], mdx: []}
const seen = new Set()
const groups = {markdown: md, html, mdx}

const alexRun = (category, text) => {
  try {
    const r = entry[category](text)
    const msgs = r.messages.map((x) => ({l: x.line, c: x.column, s: `${x.line}:${x.column}-${x.position.end.line}:${x.position.end.column}: ${x.reason} [${x.source}:${x.ruleId}]`}))
    // Stable sort by position, the order that lexi reports.
    return msgs.map((v, i) => ({...v, i})).sort((p, q) => p.l - q.l || p.c - q.c || p.i - q.i).map((v) => v.s)
  } catch (error) {
    return [`ERROR ${error.message}`]
  }
}

let n = 0
for (const category of Object.keys(groups)) {
  const tpls = groups[category]
  tpls.forEach((t, ti) => {
    if (t.soup) {
      const text = t.fn()
      const id = crypto.createHash('sha256').update(`${category}\0${text}`).digest('hex').slice(0, 10)
      if (seen.has(id)) return
      seen.add(id)
      out[category].push({id, category, kind: t.kind, label: t.label, text, want: alexRun(category, text)})
      n++
      return
    }
    // Three term pairs for each template, rotating through the term list.
    const picks = [0, 1, 2].map((k) => [TERMS[(ti * 3 + k * 5) % TERMS.length], TERMS[(ti * 7 + k * 3 + 1) % TERMS.length]])
    for (const [a, b] of picks) {
      for (const [mod, f] of mods) {
        if (skip(t.kind, mod)) continue
        // Keep the corpus lean: the unusual modifiers apply to every other pair.
        if ((mod === 'indent' || mod === 'lead' || mod === 'noeol') && (a === picks[1][0] || b === picks[2][1])) continue
        if (mod === 'indent' && category !== 'markdown') continue
        const text = f(t.fn(a, b))
        const id = crypto.createHash('sha256').update(`${category}\0${text}`).digest('hex').slice(0, 10)
        if (seen.has(id)) continue
        seen.add(id)
        const want = alexRun(category, text)
        const row = {id, category, kind: t.kind, label: t.label, text, want}
        let known = t.known
        // A syntax error is a known difference only when alex stops.
        if (known === 'mdx-syntax-error' && !want[0]?.startsWith('ERROR')) known = ''
        if (mod === 'indent') known = '' // a tab turns the text into code
        known ||= (category === 'markdown' && mod === 'indent' && /\r(?!\n)/.test(text) ? 'markdown-lone-cr' : '')
        if (known) row.known = known
        out[category].push(row)
        n++
      }
    }
  })
}

